"""Conservative orphan sweep for opt-in Connector lifecycle attachments.

A FileField save precedes the *outer* PostgreSQL commit. On a late rollback,
the unreferenced blob cannot be removed by a normal exception handler. New
Connector media therefore uses a dedicated tenant-scoped storage namespace.
This scanner only inspects that namespace, never generic or legacy files.
"""
from __future__ import annotations

import re
from datetime import timedelta

from django.utils import timezone

from chatballs.conversations.models import Message
from chatballs.tenancy.database import tenant_atomic

# Names are generated by upload_paths.py; nothing from provider filenames is used
# to select a deletion candidate. Restrict to the currently supported M1 types.
_FILE_NAME = re.compile(r"[0-9a-f]{32}\.(?:jpg|jpeg|png|pdf)\Z")
DEFAULT_AGE = timedelta(hours=24)


def reconcile_connector_media_orphans(
    *, organization, delete: bool = False,
    min_age: timedelta = DEFAULT_AGE, max_files: int = 1000,
) -> dict[str, int]:
    """Report or remove aged, unreferenced blobs in the *active* storage.

    Defaults to read-only. Only a uniquely named staged Connector attachment
    which is older than min_age AND not referenced by ANY native Message in
    the organization can be removed. Never touches ordinary /files or /voice.
    """
    if min_age < timedelta(hours=1):
        raise ValueError("min_age must be at least one hour")
    if max_files < 1:
        raise ValueError("max_files must be positive")

    counts = {
        "scanned": 0, "candidates": 0, "deleted": 0,
        "protected": 0, "recent": 0, "ignored": 0, "truncated": 0,
    }
    cutoff = timezone.now() - min_age
    prefix = f"organizations/{organization.public_id}/connector-media"
    with tenant_atomic(organization.id):
        storage = Message._meta.get_field("attachment").storage
        try:
            folders, _ = storage.listdir(prefix)
        except FileNotFoundError:
            return counts

        for folder in sorted(folders):
            if not folder.isdecimal() or int(folder) < 1:
                counts["ignored"] += 1
                continue
            folder_path = f"{prefix}/{folder}"
            try:
                _, files = storage.listdir(folder_path)
            except FileNotFoundError:
                continue
            for filename in sorted(files):
                counts["scanned"] += 1
                if counts["scanned"] > max_files:
                    counts["truncated"] = 1
                    return counts
                if _FILE_NAME.fullmatch(filename) is None:
                    counts["ignored"] += 1
                    continue
                name = f"{folder_path}/{filename}"
                try:
                    modified = storage.get_modified_time(name)
                except FileNotFoundError:
                    # A concurrent cleanup may have removed the object already.
                    continue
                if timezone.is_naive(modified):
                    modified = timezone.make_aware(modified)
                if modified >= cutoff:
                    counts["recent"] += 1
                    continue
                # Check all native references, not just READY connector rows.
                # A rollback leaves no Message. Pending commits are protected
                # by the 24h grace period (or explicitly supplied min_age).
                if Message.objects.filter(attachment=name).exists():
                    counts["protected"] += 1
                    continue
                counts["candidates"] += 1
                if delete:
                    # Re-check immediately before deleting; this is maintenance
                    # on files created long before any in-flight transaction.
                    if Message.objects.filter(attachment=name).exists():
                        counts["candidates"] -= 1
                        counts["protected"] += 1
                        continue
                    storage.delete(name)
                    counts["deleted"] += 1
    return counts
