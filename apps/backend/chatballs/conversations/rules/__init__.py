"""Правила обработки обращений по событиям и срокам (SPEC-0034).

Настройка правила, журнал его исполнений и общий исполнитель отложенных
действий. Что в каком модуле:

* ``models`` — правило организации и запись журнала;
* ``catalog``, ``conditions`` — что можно настроить у каждого правила и как
  проверяются условия;
* ``settings`` — чтение и изменение настроек с версией;
* ``scheduler`` — постановка, перенос и снятие отложенного действия;
* ``reconcile`` — общий шаг: согласовать отложенные действия с диалогом;
* ``planning`` — факты и сообщения клиента как повод для этого шага;
* ``executor`` — проверка и выполнение действия в срок;
* ``assignment_return`` — возврат назначенного непринятого обращения;
* ``receipt_confirmation``, ``deadline_text``, ``message_delivery`` —
  подтверждение получения клиенту и его отправка;
* ``wait_notice``, ``reply_reminder``, ``recipients`` — уведомления
  сотрудникам и выбор получателей;
* ``journal``, ``views`` — журнал исполнений и HTTP API.
"""
